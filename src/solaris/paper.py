        e = d.svf_engine_a_2 - d.svf_image
        m[name("EeightSvf", tag, "N")] = len(d)
        m[name("EeightSvf", tag, "Mae")] = f(e.abs().mean(), 3)
        m[name("EeightSvf", tag, "Rmse")] = f(np.sqrt((e**2).mean()), 3)
        m[name("EeightSvf", tag, "R")] = f(np.corrcoef(d.svf_image, d.svf_engine_a_2)[0, 1], 2)


