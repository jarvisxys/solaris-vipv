def name(*parts) -> str:
    """LaTeX command name from parts: digits spelled out, everything else but letters dropped."""
    s = "".join(str(p) for p in parts)
    s = "".join(DIGITS[int(c)].capitalize() if c.isdigit() else c for c in s)
    s = re.sub(r"[^A-Za-z]", "", s)
    if not s:
        raise ValueError(parts)
    return s


def f(x, nd):
    """Fixed decimals with a true minus sign for negative values."""
    s = f"{float(x):.{nd}f}"
    return s.replace("-", "\\textminus{}") if s.startswith("-") else s


def pct(x, nd=0):
    return f(100 * float(x), nd)


def sci(x):
    """One significant digit times a power of ten, usable in text and math."""
    mant, exp = f"{float(x):.0e}".split("e")
    return f"\\ensuremath{{{mant}\\times10^{{{int(exp)}}}}}"


def thousands(x):
    return f"{round(float(x)):,}".replace(",", "{,}")


def status(ok):
    return "met" if ok else "not met"


class Macros(dict):
    def __setitem__(self, k, v):
        if k in self:
            raise KeyError(f"duplicate macro {k}")
        if not re.fullmatch(r"[A-Za-z]+", k):
            raise ValueError(k)
        super().__setitem__(k, str(v))

    def tex(self) -> str:
        head = "% Generated by solaris.paper.macros from results/. Do not edit.\n"
        return head + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in sorted(self.items()))


