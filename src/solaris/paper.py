    m["GeoTiles"] = g["aoi"]["tiles"]
    m["GeoPoints"] = f(g["lidar"]["points_kept"] / 1e9, 2)
    m["GeoDensity"] = f(g["lidar"]["points_per_m2"], 1)
    for k, v in g["classes_pct"].items():
        m[name("GeoPct", k.capitalize())] = f(v, 1)
    m["GeoHoles"] = f(g["dsm_holes_pct"], 2)
    m["GeoOverture"] = thousands(g["sources"]["overture_buildings"])
    gc = g["ground_control"]
    m["GeoMarks"] = gc["n_marks"]
    m["GeoMarkMedian"] = f(gc["median_m"], 2)
    m["GeoMarkMad"] = f(gc["mad_m"], 2)
    m["GeoMarkWithin"] = f(gc["within_0p5m_pct"], 0)
    for k, v in g["freshness_confirmed"].items():
        m[name("Fresh", k.capitalize())] = v
    n = sum(g["freshness_candidates"].values())
    m["FreshCandidates"] = n
    m["FreshReviewed"] = sum(g["freshness_confirmed"].values())
