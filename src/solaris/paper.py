    t = t.set_index(["city", "scenario", "metric"])
    for city, c in CITIES.items():
        for sc in ("II", "I"):

            def g(k, city=city, sc=sc):
                return float(t.loc[(city, sc, k), "tmy"])

            p = name("Bz", c, sc)
            m[p + "fss"] = f(g("fss"), 3)
            m[p + "fssTwo"] = f(g("fss"), 2)
            m[p + "charges"] = int(g("charges_per_yr"))
            m[p + "chargesNoSolar"] = int(g("charges_nosolar_per_yr"))
            m[p + "chargeCut"] = f(g("charge_reduction_pct"), 0)
            m[p + "relief"] = f(g("relief_pct"), 0)
            m[p + "grid"] = thousands(g("grid_kWh"))
            m[p + "demand"] = thousands(g("demand_kWh"))
            m[p + "Areq"] = f(g("A_req_m2"), 1)
            m[p + "Dmax"] = f(g("D_max_km_day"), 1)
            m[p + "payFull"] = f(g("payback_full_yr"), 1)
            m[p + "payPV"] = f(g("payback_pvonly_yr"), 1)
            m[p + "fssSyn"] = f(float(t.loc[(city, sc, "fss"), "synthetic"]), 2)
            m[p + "class"] = t.loc[(city, sc, "fss_class"), "tmy"]
        m[name("Bz", c, "ghi")] = f(t.loc[(city, "II", "ghi_kWh_m2"), "tmy"], 1)
        m[name("Bz", c, "psh")] = f(t.loc[(city, "II", "psh"), "tmy"], 2)
        m[name("Bz", c, "Tmean")] = f(t.loc[(city, "II", "T_mean_C"), "tmy"], 1)
    s = _json("e0/summary_b0.json")
    for city, c in CITIES.items():
        gd = s["gap_decomposition_II"][city]
        for k in ("magnitude", "distribution", "total"):
            m[name("Gap", c, k.capitalize())] = f(gd[k], 3)
    rel = [r for r in s["tmy_releases_phoenix"] if r["scenario"].startswith("II")]
    m["BzRelLo"] = f(min(r["fss"] for r in rel), 3)
    m["BzRelHi"] = f(max(r["fss"] for r in rel), 3)
    m["BzAreaFssOne"] = f(s["design_levers_phoenix_II"]["area_for_fss1_m2"], 1)
    from .core import whkm

    m["BzWhkmCity"] = f(whkm("P0", city=True), 0)
    m["BzWhkmFull"] = f(whkm("P0", city=False), 0)


